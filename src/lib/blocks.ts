// The standard pieces of a system design. The palette above the canvas and the Learn page use this list.

export type BlockGroup = {
  id: string;
  title: string;
  summary: string;
  // The fill color of the piece on the canvas and in the palette.
  color: string;
};

// The form on the canvas. The first five are components. The others are arrows, frames, and sets of pieces.
export type BlockShape =
  | "box"
  | "person"
  | "actor"
  | "device"
  | "module"
  | "store"
  | "pipe"
  | "external"
  | "call"
  | "message"
  | "replication"
  | "boundary"
  | "pattern";

// The three connections of the palette. Each has its own line style.
export type LinkKind = "call" | "message" | "replication";

// A small set of pieces that often come together, with the arrows between them.
export type Pattern = {
  // Each piece has a key, the ID of its block, and a place in a grid.
  pieces: { key: string; block: string; col: number; row: number }[];
  links: { from: string; to: string; kind: LinkKind }[];
};

export type Block = {
  id: string;
  name: string;
  group: string;
  // The form on the canvas. It follows the usual notation: a cylinder for stored data, a pipe for messages.
  shape: BlockShape;
  // What the piece does.
  does: string;
  // The signal in a problem that calls for the piece.
  useWhen: string;
  // What you pay when you add the piece.
  cost: string;
  // A question that the rationale must answer when the piece is in the design.
  question: string;
  // The slug of the lesson with more detail.
  learn: string;
  // Set when the shape is "pattern".
  pattern?: Pattern;
};

